// vibe-spec: literal-file
//! Generates the flow parity corpus (`tests/parity/corpus/flow/`).
//!
//! Deterministic: the same `flow/` half always gives the same bytes. Classes:
//! - `paths` — one case per shipped policy match entry (queries derived from
//!   the entry: a literal queries itself, a glob queries its pinned
//!   representative) plus one case per spelling variant and an unmatched
//!   control; each case runs `policy decide` over every machine state.
//! - `mutated` — one policy mutation per defect class; runs pick states that
//!   flip at least one verdict against the shipped rules (or hit the refusal
//!   path the mutation must produce).
//! - `corrupt` — policy files no engine may load.
//! - `cursors` — `state get` over every machine state plus feature shapes,
//!   per-field defaults and corrupt documents.
//! - `edges` — one case per legal `next` entry of every state, derived from
//!   the machine.
//! - `errors` — `state set` failure shapes.
//! - `guard` — guard stdin shapes: allow, block, the live cursor, and a
//!   warn-only Bash redirect.
//! - `stop` — receipt tooth shapes: inactive, missing, fresh, stale (real
//!   git + stamps), TDD warn, and the `.vibe/run/**` own-runtime exclusion.
use std::fs;
use std::path::Path;

use serde_json::{Map, Value, json};

/// Marker file at the corpus root; the generator only replaces a directory that holds it.
pub const MARKER: &str = ".generated";
const MARKER_TEXT: &str = "Generated by `vibe-parity gen-flow-corpus`. Do not edit; regenerate.\n";

const POLICY_TREE: &str = ".agents/skills/vibe/content/policy.json";
const MACHINE_TREE: &str = ".agents/skills/vibe/state-machine.json";
const CURSOR_TREE: &str = ".agents/skills/vibe/state.json";
const DETECT_TREE: &str = ".agents/skills/vibe/scripts/detect-context.sh";
const EVIDENCE_TREE: &str = ".agents/skills/vibe/evidence";
const UPDATED: &str = "2026-01-01T00:00:00Z";

type Files = Vec<(String, String)>;
type Runs = Vec<(String, Vec<Vec<String>>)>;

struct CaseDef {
    class: &'static str,
    name: String,
    runs: Runs,
    files: Files,
}

struct RawCase {
    class: &'static str,
    name: String,
    json: Value,
    files: Files,
}

fn cursor(flow: &str, phase: &str, feature: Value) -> String {
    format!(
        "{{\"flow\":\"{flow}\",\"phase\":\"{phase}\",\"feature\":{feature},\"updated\":\"{UPDATED}\"}}\n"
    )
}

fn policy_case(name: &str, policy: &str, runs: Runs) -> CaseDef {
    CaseDef {
        class: "paths",
        name: name.to_string(),
        runs,
        files: vec![(POLICY_TREE.to_string(), policy.to_string())],
    }
}

/// The pinned representative query for a shipped glob. A new glob rule with
/// no entry here fails generation on purpose: a glob's corpus query is a
/// judgement (which path proves the `*` spans `/`), not something to guess.
fn glob_query(pattern: &str) -> Option<&'static str> {
    match pattern {
        ".planning/*" => Some(".planning/STATE.md"),
        ".spec/features/*" => Some(".spec/features/auth/tech.md"),
        "docs/spec/features/*" => Some("docs/spec/features/auth/tech.md"),
        "docs/superpowers/specs/*" => Some("docs/superpowers/specs/auth-design.md"),
        "src/*" => Some("src/a.rs"),
        "tests/*" => Some("tests/b.rs"),
        _ => None,
    }
}

fn split_state(key: &str) -> (&str, &str) {
    match key.split_once('.') {
        Some((flow, phase)) => (flow, phase),
        None => (key, key),
    }
}

/// One `[path, state]` pair for every state of the machine, sorted.
fn all_states(path: &str, states: &[String]) -> Vec<Vec<String>> {
    states
        .iter()
        .map(|state| vec![path.to_string(), state.clone()])
        .collect()
}

fn refusal_runs() -> Runs {
    vec![(
        "policy-decide".to_string(),
        vec![
            vec!["src/a.rs".to_string(), "idle".to_string()],
            vec!["docs/spec/tech.md".to_string(), "idle".to_string()],
            vec!["nope.md".to_string(), "feature.impl".to_string()],
        ],
    )]
}

/// The shipped policy with `edit` applied, as deterministic pretty JSON.
fn mutated_policy(shipped: &Value, edit: impl FnOnce(&mut Map<String, Value>)) -> String {
    let mut object = shipped.as_object().cloned().unwrap_or_default();
    edit(&mut object);
    format!(
        "{}\n",
        serde_json::to_string_pretty(&Value::Object(object)).unwrap_or_default()
    )
}

/// The rules array of `object`, mutable; rules keep their file order.
fn rules_mut(object: &mut Map<String, Value>) -> Vec<&mut Map<String, Value>> {
    object
        .get_mut("rules")
        .and_then(Value::as_array_mut)
        .map(|list| {
            list.iter_mut()
                .filter_map(Value::as_object_mut)
                .collect::<Vec<_>>()
        })
        .unwrap_or_default()
}

fn rule_mut<'a>(
    rules: &'a mut [&mut Map<String, Value>],
    id: &str,
) -> Option<&'a mut Map<String, Value>> {
    rules
        .iter_mut()
        .find(|rule| rule.get("id").and_then(Value::as_str) == Some(id))
        .map(|rule| &mut **rule)
}

fn arm(rule: &mut Map<String, Value>, index: usize) -> Option<&mut Map<String, Value>> {
    rule.get_mut("arms")
        .and_then(Value::as_array_mut)
        .and_then(|arms| arms.get_mut(index))
        .and_then(Value::as_object_mut)
}

fn cases(flow_dir: &Path) -> Result<Vec<CaseDef>, String> {
    let policy_path = flow_dir.join("content").join("policy.json");
    let shipped_text =
        fs::read_to_string(&policy_path).map_err(|e| format!("{}: {e}", policy_path.display()))?;
    let shipped: Value = serde_json::from_str(&shipped_text)
        .map_err(|e| format!("{}: {e}", policy_path.display()))?;
    let machine_path = flow_dir.join("state-machine.json");
    let machine: Value = serde_json::from_str(
        &fs::read_to_string(&machine_path)
            .map_err(|e| format!("{}: {e}", machine_path.display()))?,
    )
    .map_err(|e| format!("{}: {e}", machine_path.display()))?;
    let machine_text = fs::read_to_string(&machine_path)
        .map_err(|e| format!("{}: {e}", machine_path.display()))?;
    let mut states: Vec<String> = machine
        .get("states")
        .and_then(Value::as_object)
        .map(|states| states.keys().cloned().collect())
        .unwrap_or_default();
    states.sort();
    if states.is_empty() {
        return Err(format!("{}: no states", machine_path.display()));
    }

    let mut defs = Vec::new();

    // paths: one case per shipped match entry, queries derived from the data.
    let Some(Value::Array(shipped_rules)) = shipped.get("rules") else {
        return Err(format!("{}: no rules array", policy_path.display()));
    };
    for rule in shipped_rules {
        let Some(id) = rule.get("id").and_then(Value::as_str) else {
            continue;
        };
        let Some(matches) = rule.get("match") else {
            continue;
        };
        let entries: Vec<&str> = match matches {
            Value::Array(list) => list.iter().filter_map(Value::as_str).collect(),
            Value::String(text) => vec![text.as_str()],
            _ => continue,
        };
        for (idx, entry) in entries.iter().enumerate() {
            let query = if entry.contains('*') || entry.contains('?') {
                glob_query(entry).ok_or_else(|| {
                    format!("policy: glob {entry:?} (rule {id:?}) has no pinned corpus query")
                })?
            } else {
                entry
            };
            let name = if entries.len() == 1 {
                format!("entry-{id}")
            } else {
                format!("entry-{id}-{idx}")
            };
            defs.push(policy_case(
                &name,
                &shipped_text,
                vec![("policy-decide".to_string(), all_states(query, &states))],
            ));
        }
    }

    // paths: spelling variants and the unmatched control.
    for (name, path) in [
        ("spell-dot-slash", "./docs/spec/lessons.md"),
        ("spell-absolute", "/docs/spec/lessons.md"),
        ("spell-nested-extra-dir", "sub/docs/spec/lessons.md"),
        ("spell-segments", "docs//spec/./lessons.md"),
        ("spell-dotdot-collapse", "sub/../docs/spec/lessons.md"),
        ("control-unmatched", "nope.md"),
    ] {
        defs.push(policy_case(
            name,
            &shipped_text,
            vec![("policy-decide".to_string(), all_states(path, &states))],
        ));
    }

    // mutated: one defect class per case.
    let mut mutated = |name: &str, edit: fn(&mut Map<String, Value>), runs: Runs| {
        defs.push(CaseDef {
            class: "mutated",
            name: name.to_string(),
            runs,
            files: vec![(POLICY_TREE.to_string(), mutated_policy(&shipped, edit))],
        });
    };
    mutated(
        "drop-lessons-allow",
        |object| {
            let mut rules = rules_mut(object);
            if let Some(rule) = rule_mut(&mut rules, "lessons")
                && let Some(arms) = rule.get_mut("arms").and_then(Value::as_array_mut)
            {
                arms.remove(0);
            }
        },
        vec![(
            "policy-decide".to_string(),
            vec![
                vec![
                    ".spec/lessons.md".to_string(),
                    "feature.compound".to_string(),
                ],
                vec![".spec/lessons.md".to_string(), "quick.verify".to_string()],
                vec![".spec/lessons.md".to_string(), "idle".to_string()],
            ],
        )],
    );
    mutated(
        "invert-warn-block",
        |object| {
            let mut rules = rules_mut(object);
            if let Some(rule) = rule_mut(&mut rules, "features-frozen") {
                for index in [0, 1] {
                    if let Some(arm) = arm(rule, index) {
                        let verdict = match arm.get("verdict").and_then(Value::as_str) {
                            Some("warn") => "allow",
                            Some("allow") => "warn",
                            other => other.unwrap_or("block"),
                        };
                        arm.insert("verdict".to_string(), json!(verdict));
                    }
                }
            }
        },
        vec![(
            "policy-decide".to_string(),
            vec![
                vec![
                    ".spec/features/x/tech.md".to_string(),
                    "feature.impl".to_string(),
                ],
                vec![
                    ".spec/features/x/tech.md".to_string(),
                    "quick.fix".to_string(),
                ],
                vec![".spec/features/x/tech.md".to_string(), "idle".to_string()],
            ],
        )],
    );
    mutated(
        "unknown-state-arm",
        |object| {
            let mut rules = rules_mut(object);
            if let Some(rule) = rule_mut(&mut rules, "gsd-planning")
                && let Some(arm) = arm(rule, 0)
            {
                arm.insert("states".to_string(), json!(["made.up.state"]));
            }
        },
        vec![(
            "policy-decide".to_string(),
            vec![
                vec![".planning/STATE.md".to_string(), "idle".to_string()],
                vec![".planning/STATE.md".to_string(), "feature.impl".to_string()],
                vec![".planning/STATE.md".to_string(), "quick.fix".to_string()],
            ],
        )],
    );
    mutated(
        "glob-spans-slash",
        |object| {
            let mut rules = rules_mut(object);
            if let Some(rule) = rule_mut(&mut rules, "gsd-planning") {
                rule.insert("match".to_string(), json!(".planning/*.md"));
            }
        },
        vec![(
            "policy-decide".to_string(),
            vec![
                vec![".planning/a/b.md".to_string(), "feature.impl".to_string()],
                vec![".planning/a/b.json".to_string(), "feature.impl".to_string()],
                vec![".planning/x.md".to_string(), "idle".to_string()],
            ],
        )],
    );
    mutated(
        "missing-id",
        |object| {
            let mut rules = rules_mut(object);
            if let Some(rule) = rule_mut(&mut rules, "cursor") {
                rule.remove("id");
            }
        },
        refusal_runs(),
    );
    mutated(
        "no-arms",
        |object| {
            let mut rules = rules_mut(object);
            if let Some(rule) = rule_mut(&mut rules, "generated-docs") {
                rule.insert("arms".to_string(), json!([]));
            }
        },
        refusal_runs(),
    );
    mutated(
        "unknown-verdict",
        |object| {
            let mut rules = rules_mut(object);
            if let Some(rule) = rule_mut(&mut rules, "cursor")
                && let Some(arm) = arm(rule, 0)
            {
                arm.insert("verdict".to_string(), json!("refuse"));
            }
        },
        refusal_runs(),
    );
    mutated(
        "version-two",
        |object| {
            object.insert("version".to_string(), json!(2));
        },
        refusal_runs(),
    );
    mutated(
        "empty-rules",
        |object| {
            object.insert("rules".to_string(), json!([]));
        },
        refusal_runs(),
    );
    defs.push(CaseDef {
        class: "mutated",
        name: "truncated-json".to_string(),
        runs: refusal_runs(),
        files: vec![(
            POLICY_TREE.to_string(),
            "{ \"version\": 1, \"rules\": [\n".to_string(),
        )],
    });

    // corrupt: files no engine may load.
    for (name, body) in [("truncated", "{ \"version\": 1,\n"), ("non-object", "[]\n")] {
        defs.push(CaseDef {
            class: "corrupt",
            name: name.to_string(),
            runs: vec![(
                "policy-decide".to_string(),
                vec![
                    vec!["src/a.rs".to_string(), "idle".to_string()],
                    vec!["src/a.rs".to_string(), "feature.impl".to_string()],
                ],
            )],
            files: vec![(POLICY_TREE.to_string(), body.to_string())],
        });
    }

    // cursors: every state, feature shapes, defaults, corrupt documents.
    defs.push(CaseDef {
        class: "cursors",
        name: "absent".to_string(),
        runs: vec![("state-get".to_string(), vec![Vec::new()])],
        files: Vec::new(),
    });
    for state in &states {
        let (flow, phase) = split_state(state);
        defs.push(CaseDef {
            class: "cursors",
            name: state.clone(),
            runs: vec![("state-get".to_string(), vec![Vec::new()])],
            files: vec![(
                CURSOR_TREE.to_string(),
                cursor(
                    flow,
                    phase,
                    if state == "idle" {
                        Value::Null
                    } else {
                        json!("auth")
                    },
                ),
            )],
        });
    }
    for (name, body) in [
        ("null-feature", cursor("feature", "impl", Value::Null)),
        ("non-string-feature", cursor("feature", "impl", json!(123))),
        ("missing-keys", "{\"flow\":\"quick\"}\n".to_string()),
        ("corrupt-not-json", "{ nope\n".to_string()),
        ("corrupt-array", "[]\n".to_string()),
        ("corrupt-number", "7\n".to_string()),
    ] {
        defs.push(CaseDef {
            class: "cursors",
            name: name.to_string(),
            runs: vec![("state-get".to_string(), vec![Vec::new()])],
            files: vec![(CURSOR_TREE.to_string(), body)],
        });
    }

    // edges: one case per legal next entry, derived from the machine.
    for state in &states {
        let next = machine
            .get("states")
            .and_then(|states| states.get(state))
            .and_then(Value::as_object)
            .and_then(|entry| entry.get("next"))
            .and_then(Value::as_array)
            .map(|list| list.iter().filter_map(Value::as_str).collect::<Vec<_>>())
            .unwrap_or_default();
        for target in next {
            defs.push(CaseDef {
                class: "edges",
                name: format!("{state}__{target}"),
                runs: vec![("state-set".to_string(), vec![vec![target.to_string()]])],
                files: vec![(MACHINE_TREE.to_string(), machine_text.clone())],
            });
        }
    }

    // errors: state set failure shapes.
    let machine_files = || vec![(MACHINE_TREE.to_string(), machine_text.clone())];
    defs.push(CaseDef {
        class: "errors",
        name: "unknown-target".to_string(),
        runs: vec![("state-set".to_string(), vec![vec!["nope".to_string()]])],
        files: machine_files(),
    });
    defs.push(CaseDef {
        class: "errors",
        name: "no-target".to_string(),
        runs: vec![("state-set".to_string(), vec![Vec::new()])],
        files: machine_files(),
    });
    defs.push(CaseDef {
        class: "errors",
        name: "machine-absent".to_string(),
        runs: vec![("state-set".to_string(), vec![vec!["idle".to_string()]])],
        files: Vec::new(),
    });

    Ok(defs)
}

fn case_json(def: &CaseDef) -> Value {
    let mut runs = Map::new();
    for (command, sets) in &def.runs {
        runs.insert(command.clone(), json!(sets));
    }
    json!({ "v": 1, "runs": runs })
}

fn write(path: &Path, text: &str) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

/// Writes the corpus into `out` from the flow half in `flow_dir` (its
/// `content/policy.json` and `state-machine.json`). Refuses to touch an
/// existing `out` that lacks the [`MARKER`] file. Returns the number of cases
/// written.
pub fn generate(flow_dir: &Path, out: &Path) -> Result<usize, String> {
    let defs = cases(flow_dir)?;
    if out.exists() {
        if !out.join(MARKER).is_file() {
            return Err(format!(
                "{}: exists and holds no {MARKER}; refusing to replace it",
                out.display()
            ));
        }
        fs::remove_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    }
    write(&out.join(MARKER), MARKER_TEXT)?;
    for def in &defs {
        let dir = out.join(def.class).join(&def.name);
        let text = serde_json::to_string_pretty(&case_json(def)).map_err(|e| e.to_string())?;
        write(&dir.join("case.json"), &format!("{text}\n"))?;
        for (path, body) in &def.files {
            write(&dir.join("tree").join(path), body)?;
        }
    }
    Ok(defs.len())
}
